"""Offline whitelist enforcement. Python 3.10+, standard library only."""
from __future__ import annotations
import argparse
import fnmatch
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import stat
import subprocess
import sys

POLICY_PATH = 'tools/repository-sync-policy.json'


def git(root, *args, input=None):
    process = subprocess.run(['git', '-c', f'safe.directory={Path(root).as_posix()}',
                              '-C', str(root), *args], input=input, capture_output=True)
    if process.returncode:
        raise ValueError(process.stderr.decode('utf-8', errors='replace').strip())
    return process.stdout


def glob_regex(pattern):
    # Git-style path globs: * never crosses a slash; **/ also matches zero directories.
    parts = pattern.split('/')
    return re.compile('^' + ''.join('(?:.*/)?' if part == '**' and i < len(parts)-1 else
        '.*' if part == '**' else fnmatch.translate(part)[4:-3].replace('.*', '[^/]*') +
        ('/' if i < len(parts)-1 else '') for i, part in enumerate(parts)) + '$', re.I)


class Policy:
    def __init__(self, root, data=None):
        self.root = Path(root).resolve()
        self.data = data if data is not None else json.loads((self.root/POLICY_PATH).read_text(encoding='utf-8-sig'))
        if self.data['schemaVersion'] != 1: raise ValueError('Unknown synchronization policy version')
        self.allow = [p for group in self.data['allow'] for p in group['patterns']]
        self.deny = self.data['deny']
        self.allowed = [glob_regex(p) for p in self.allow]
        self.denied = [glob_regex(p) for p in self.deny]

    def accepts(self, name):
        if not name or any(ord(c)<32 or c in '\\:<>"|?*' for c in name) or name.startswith('/') or any(
                p in ('', '.', '..') or p.endswith((' ', '.')) for p in name.split('/')):
            return False
        return not any(p.fullmatch(name) for p in self.denied) and any(p.fullmatch(name) for p in self.allowed)

    def ignore_text(self):
        lines = ['# Generated by tools/repository-sync.ps1 -Mode GenerateIgnore; edit the JSON policy.',
                 '# Ignore files by default, allow directory traversal, then apply allow/deny rules.', '*', '!*/']
        lines += ['!/' + p for p in self.allow]
        for pattern in self.deny:
            lines.append('/' + pattern)
            if pattern.endswith('/**'): lines.append('/' + pattern[:-3] + '/')
        return '\n'.join(lines) + '\n'

    def check_entries(self, entries, context):
        names = set()
        errors = []
        for mode, name in entries:
            if not self.accepts(name): errors.append(f'Forbidden path: {name}')
            if mode not in ('100644','100755'): errors.append(f'Unsupported Git mode {mode}: {name}')
            if name.casefold() in names: errors.append(f'Case-insensitive path collision: {name}')
            names.add(name.casefold())
        if errors: raise ValueError(context + '\n' + '\n'.join(errors))

    def files(self):
        # Walk only possible public roots and prune explicitly local trees before descending.
        roots = {pattern.split('/')[0] for pattern in self.allow}
        result = []
        for first in sorted(roots):
            start = self.root/first
            if start.is_file():
                if self.accepts(first): result.append(start)
                continue
            if not start.exists(): continue
            for base, dirs, files in os.walk(start, followlinks=False):
                dirs[:] = [d for d in dirs if not any(p.fullmatch((Path(base)/d).relative_to(self.root).as_posix()+'/') for p in self.denied)]
                for directory in dirs:
                    if is_link(Path(base)/directory): raise ValueError(f'Links/junctions cannot be exported: {Path(base)/directory}')
                for name in files:
                    p = Path(base)/name
                    if self.accepts(p.relative_to(self.root).as_posix()): result.append(p)
        for path in result:
            if any(is_link(p) for p in (path,*path.parents) if p != self.root and self.root in p.parents):
                raise ValueError(f'Links/junctions cannot be exported: {path}')
        return sorted(result)


def is_link(path):
    return path.is_symlink() or bool(getattr(path.lstat(),'st_file_attributes',0) & getattr(stat,'FILE_ATTRIBUTE_REPARSE_POINT',0))


def tree_entries(root, revision):
    result = []
    for record in git(root, 'ls-tree', '-r', '-z', revision).split(b'\0'):
        if not record: continue
        meta, name = record.split(b'\t',1)
        result.append((meta.split()[0].decode(), name.decode('utf-8')))
    return result


def check_commit(policy, revision):
    policy.check_entries(tree_entries(policy.root, revision), f'Commit {revision}')


def check_staged(policy):
    entries=[]
    for record in git(policy.root, 'ls-files', '--stage', '-z').split(b'\0'):
        if not record: continue
        meta,name=record.split(b'\t',1)
        mode, _, stage = meta.split()
        if stage != b'0': raise ValueError('Resolve index conflicts before committing')
        entries.append((mode.decode(),name.decode('utf-8')))
    policy.check_entries(entries,'Staged index')
    staged_policy = Policy(policy.root,json.loads(git(policy.root,'show',':'+POLICY_PATH)))
    # Both the current and staged policy must accept the complete index.
    staged_policy.check_entries(entries,'Staged policy')
    actual=git(policy.root,'show',':.gitignore').decode().replace('\r\n','\n')
    if actual != staged_policy.ignore_text(): raise ValueError('Staged .gitignore is not generated from staged policy')


def check_history(policy, head='HEAD', base=None):
    args=['rev-list',head]
    if base and set(base) != {'0'}:
        # A missing baseline must fail closed; never silently skip unknown history.
        git(policy.root,'rev-parse','--verify',base+'^{commit}')
        args += ['--not',base]
    commits=git(policy.root,*args).decode().splitlines()
    for commit in commits: check_commit(policy,commit)
    return len(commits)


def export_tree(policy, destination):
    target=Path(destination).resolve()
    if target == policy.root or target in policy.root.parents: raise ValueError('Export target cannot contain source')
    if target.exists() and any(target.iterdir()): raise ValueError('Export requires an empty destination')
    files=policy.files()
    policy.check_entries([('100644',p.relative_to(policy.root).as_posix()) for p in files],'Export')
    if target in files or any(target in p.parents for p in files): raise ValueError('Export target overlaps public source')
    target.mkdir(parents=True,exist_ok=True)
    manifest=[]
    for source in files:
        rel=source.relative_to(policy.root)
        dest=target/rel; dest.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(source,dest)
        digest=hashlib.sha256(source.read_bytes()).hexdigest()
        if hashlib.sha256(dest.read_bytes()).hexdigest()!=digest: raise ValueError(f'Export checksum mismatch: {rel}')
        manifest.append({'path':rel.as_posix(),'sha256':digest,'bytes':source.stat().st_size})
    # Keep export evidence outside the tree that will become the public repository.
    report=target.parent/(target.name+'.manifest.json')
    report.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return len(manifest)


def install_hooks(policy):
    configured=subprocess.run(['git','-c',f'safe.directory={policy.root.as_posix()}',
                               '-C',str(policy.root),'config','--get','core.hooksPath'],capture_output=True)
    if configured.returncode not in (0,1): raise ValueError('Cannot read Git hooks configuration')
    if configured.stdout.strip(): raise ValueError('Existing core.hooksPath is configured; integrate hooks explicitly instead of replacing it')
    hooks=Path(git(policy.root,'rev-parse','--git-path','hooks').decode().strip())
    if not hooks.is_absolute(): hooks=policy.root/hooks
    hooks.mkdir(parents=True,exist_ok=True)
    marker='# Simpilot repository-sync hook'
    for name in ('pre-commit','pre-push'):
        path=hooks/name
        if path.exists() and marker not in path.read_text(encoding='utf-8'): raise ValueError(f'Existing custom hook: {path}')
    for name,mode in [('pre-commit','Staged'),('pre-push','Hook')]:
        path=hooks/name
        path.write_text('#!/bin/sh\n'+marker+'\nroot=$(git rev-parse --show-toplevel) || exit 1\nexec pwsh -NoProfile -File "$root/tools/repository-sync.ps1" -Mode '+mode+' -Root "$root"\n',encoding='utf-8',newline='\n')
        path.chmod(0o755)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root',default=str(Path(__file__).resolve().parents[1]))
    p.add_argument('--mode',choices=['Worktree','Staged','Commit','History','Hook','Export','GenerateIgnore','InstallHooks'],required=True)
    p.add_argument('--revision',default='HEAD'); p.add_argument('--base'); p.add_argument('--destination')
    a=p.parse_args(); policy=Policy(a.root)
    if a.mode=='GenerateIgnore': (policy.root/'.gitignore').write_text(policy.ignore_text(),encoding='utf-8',newline='\n')
    elif a.mode=='InstallHooks': install_hooks(policy)
    elif a.mode=='Staged': check_staged(policy)
    elif a.mode=='Commit': check_commit(policy,a.revision)
    elif a.mode=='History': print(f'Checked {check_history(policy,a.revision,a.base)} outgoing commits')
    elif a.mode=='Hook':
        for line in sys.stdin:
            fields=line.split()
            if len(fields)!=4: raise ValueError('Invalid pre-push input')
            _,head,_,base=fields
            if set(head)=={'0'}: continue
            check_history(policy,head,None if set(base)=={'0'} else base)
    elif a.mode=='Export':
        if not a.destination: raise ValueError('--destination required')
        print(f'Exported {export_tree(policy,a.destination)} verified files')
    else:
        policy.check_entries([('100644',f.relative_to(policy.root).as_posix()) for f in policy.files()],'Public worktree')
        if (policy.root/'.gitignore').read_text(encoding='utf-8')!=policy.ignore_text(): raise ValueError('Regenerate .gitignore from policy')
    print(f'Repository synchronization check passed ({a.mode}).')


if __name__=='__main__':
    try: main()
    except (ValueError,OSError,KeyError) as e: print(str(e),file=sys.stderr); sys.exit(1)
